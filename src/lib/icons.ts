export function icon(name: IconName, size = 16, className = ''): SVGElement {
  const node = ICONS[name] ?? ICONS.circle;
  const svg = createElement(node, {
    width: String(size),
    height: String(size),
    'stroke-width': '1.75',
    'aria-hidden': 'true',
    focusable: 'false',
    class: className,
  }) as SVGElement;
  return svg;
}

export function fileIcon(path: string): IconName {
  const lower = path.toLowerCase();
  if (/\.(ts|tsx|js|jsx|mjs|cjs)$/.test(lower)) return 'file-code';
  if (/\.(json|jsonc)$/.test(lower)) return 'file-json';
  if (/\.(md|markdown|txt|log)$/.test(lower)) return 'file-text';
  if (/\.(png|jpe?g|gif|webp|svg|ico|bmp)$/.test(lower)) return 'file-image';
  if (/\.(zip|tar|gz|tgz|wasm)$/.test(lower)) return 'file-archive';
  return 'file';
}

export function iconForLanguage(language: string): IconName {
  switch (language) {
    case 'typescript':
    case 'javascript':
      return 'file-code';
    case 'json':
      return 'file-json';
    case 'markdown':
      return 'file-text';
    case 'html':
    case 'css':
      return 'file-code';
    default:
      return 'file';
  }
}
